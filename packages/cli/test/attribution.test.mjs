/**
 * ADR-005 section 2: harness-run classification and the minimal attribution
 * of temp-cwd sessions to the launched repo. Fixtures: the Claude harness and
 * temp-copy sessions from test/fixtures/claude/make-fixtures.mjs, parsed by the
 * real adapter, indexed with the real `buildEntry`, and matched against a
 * temporary repo whose files and instruction chain the test writes.
 */
